print("Starting image download & deduplication verification...")

downloaded_hashes = {}
final_cards = []

for card in CURATED_VINTAGE_CARDS:
    card_id = card["id"]
    remote_url = card.pop("remote_img")
    target_path_pub = f"public/assets/cards/{card_id}.webp"
    target_path_assets = f"assets/cards/{card_id}.webp"
    
    print(f"Downloading {card_id} [{card['character']}]: {remote_url}")
    req = urllib.request.Request(remote_url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = resp.read()
            img_hash = hashlib.md5(data).hexdigest()
            
            if img_hash in downloaded_hashes:
                print(f"  [WARNING] Duplicate image detected! Hash {img_hash} matches {downloaded_hashes[img_hash]}. SKIPPING!")
                continue
                
            downloaded_hashes[img_hash] = card_id
            
            with open(target_path_pub, "wb") as f:
                f.write(data)
            with open(target_path_assets, "wb") as f:
                f.write(data)
            print(f"  -> Saved {len(data):,} bytes (MD5: {img_hash[:8]}...)")
            final_cards.append(card)
    except Exception as e:
        print(f"  [ERROR] downloading {card_id}: {e}")

print(f"\nSuccessfully downloaded {len(final_cards)} cards with 100% unique images!")

